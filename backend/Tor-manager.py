#!/usr/bin/env python3
"""
Tor-manager.py — run local Tor instances pinned to specific countries and feed
their SOCKS5 endpoints to the Proxy Generator pool.

Why: Tor exits live in many countries. With `ExitNodes {cc}` + `StrictNodes 1`
each Tor instance keeps its exit inside one country, so the proxy service can
serve country-specific requests (e.g. /fetch with country=DE) without any paid
provider. One instance = one country = one local SOCKS5 port.

Usage (Windows):
    venv\\Scripts\\python.exe Tor-manager.py                     # countries from tor-countries.txt
    venv\\Scripts\\python.exe Tor-manager.py --countries us,de,jp
    venv\\Scripts\\python.exe Tor-manager.py --status
    venv\\Scripts\\python.exe Tor-manager.py --stop

What it writes:
    tor-proxies.txt         socks5://127.0.0.1:9701|us  (read by the proxy
                            service every cycle — no service restart needed)
    tor-data/manager.json   running instance list (pid/port/country)
    tor-data/<cc>/tor.log   per-instance log (bootstrapping progress)

Tor binary: put the Tor Expert Bundle under .\\tor (tor\\tor\\tor.exe) or pass
--tor-exe. Download: https://www.torproject.org/download/tor/
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import signal
import subprocess
import sys
import time
from pathlib import Path

PROJECT_DIR = (
    Path(__file__).resolve().parent.parent
    if Path(__file__).resolve().parent.name == "backend"
    else Path(__file__).resolve().parent
)
TOR_ROOT = PROJECT_DIR / "tor"
TOR_DATA = PROJECT_DIR / "tor-data"
PROXIES_FILE = PROJECT_DIR / "tor-proxies.txt"
COUNTRIES_FILE = PROJECT_DIR / "tor-countries.txt"
MANAGER_STATE = TOR_DATA / "manager.json"
DEFAULT_COUNTRIES = ["us", "de", "nl", "jp"]


def find_tor_exe(explicit: str | None = None) -> Path | None:
    candidates: list[Path] = []
    if explicit:
        candidates.append(Path(explicit))
    candidates += [
        TOR_ROOT / "tor" / "tor.exe",
        TOR_ROOT / "tor.exe",
        TOR_ROOT / "tor" / "tor",
        TOR_ROOT / "tor",
    ]
    which = shutil.which("tor")
    if which:
        candidates.append(Path(which))
    for candidate in candidates:
        try:
            if candidate and candidate.is_file():
                return candidate
        except OSError:
            continue
    return None


def find_geoip() -> Path | None:
    for rel in ("data/geoip", "tor/data/geoip", "geoip"):
        candidate = TOR_ROOT / rel
        if candidate.is_file():
            return candidate
    return None


def is_pid_alive(pid: int) -> bool:
    if pid <= 0:
        return False
    if os.name == "nt":
        try:
            out = subprocess.run(
                ["tasklist", "/FI", f"PID eq {pid}", "/NH"],
                capture_output=True,
                text=True,
                timeout=10,
            )
        except (OSError, subprocess.SubprocessError):
            return False
        return str(pid) in out.stdout
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


def kill_pid(pid: int) -> None:
    if os.name == "nt":
        subprocess.run(
            ["taskkill", "/PID", str(pid), "/F"],
            capture_output=True,
            text=True,
        )
    else:
        try:
            os.kill(pid, signal.SIGTERM)
        except OSError:
            pass


def load_state() -> dict:
    try:
        return json.loads(MANAGER_STATE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"instances": []}


def save_state(instances: list[dict]) -> None:
    TOR_DATA.mkdir(parents=True, exist_ok=True)
    MANAGER_STATE.write_text(
        json.dumps({"instances": instances}, indent=2), encoding="utf-8"
    )


def read_countries(explicit: str | None) -> list[str]:
    if explicit:
        raw = [part.strip().lower() for part in explicit.split(",")]
    elif COUNTRIES_FILE.exists():
        raw = [
            line.split("#", 1)[0].strip().lower()
            for line in COUNTRIES_FILE.read_text(encoding="utf-8").splitlines()
        ]
    else:
        raw = list(DEFAULT_COUNTRIES)
    codes: list[str] = []
    for code in raw:
        if len(code) == 2 and code.isalpha() and code not in codes:
            codes.append(code)
    return codes


def write_proxies_file(instances: list[dict]) -> None:
    lines = [
        "# Generated by Tor-manager.py — format: socks5://127.0.0.1:PORT|country",
    ]
    for inst in instances:
        lines.append(f"socks5://127.0.0.1:{inst['port']}|{inst['country']}")
    PROXIES_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def bootstrap_state(country: str) -> str:
    log = TOR_DATA / country / "tor.log"
    try:
        text = log.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return "no-log"
    if "Bootstrapped 100%" in text:
        return "ready"
    return "starting"


def cmd_status() -> None:
    state = load_state()
    instances = state.get("instances", [])
    if not instances:
        print("No Tor instances recorded. Start with: python Tor-manager.py")
        return
    for inst in instances:
        alive = is_pid_alive(int(inst.get("pid", 0)))
        status = bootstrap_state(inst["country"]) if alive else "dead"
        print(
            f"{inst['country'].upper()}  port={inst['port']}  pid={inst['pid']}  "
            f"alive={alive}  status={status}"
        )


def cmd_stop() -> None:
    state = load_state()
    stopped = 0
    for inst in state.get("instances", []):
        pid = int(inst.get("pid", 0))
        if is_pid_alive(pid):
            kill_pid(pid)
            stopped += 1
            print(f"stopped {inst['country'].upper()} (pid={pid})")
    save_state([])
    if PROXIES_FILE.exists():
        PROXIES_FILE.unlink()
    print(f"Done. {stopped} instance(s) stopped, tor-proxies.txt removed.")


def cmd_start(args: argparse.Namespace) -> None:
    tor_exe = find_tor_exe(args.tor_exe)
    if not tor_exe:
        print(
            "ERROR: tor.exe not found.\n"
            "Download the Tor Expert Bundle from https://www.torproject.org/download/tor/\n"
            "and extract it so that './tor/tor/tor.exe' exists, or pass --tor-exe PATH."
        )
        sys.exit(1)

    geoip = find_geoip()
    countries = read_countries(args.countries)
    if not countries:
        print("ERROR: no valid 2-letter country codes (see tor-countries.txt).")
        sys.exit(1)

    TOR_DATA.mkdir(parents=True, exist_ok=True)
    state = load_state()
    alive_existing = {
        inst["country"]: inst
        for inst in state.get("instances", [])
        if is_pid_alive(int(inst.get("pid", 0)))
    }

    # Managed set semantics: anything running but not requested gets stopped.
    for country in list(alive_existing):
        if country not in countries:
            print(f"[{country.upper()}] stopping (not in requested set)")
            kill_pid(int(alive_existing[country]["pid"]))
            alive_existing.pop(country, None)

    instances: list[dict] = []
    for index, country in enumerate(countries):
        if country in alive_existing:
            instances.append(alive_existing[country])
            print(
                f"[{country.upper()}] already running port={alive_existing[country]['port']} "
                f"pid={alive_existing[country]['pid']}"
            )
            continue

        port = args.base_port + index
        data_dir = TOR_DATA / country
        data_dir.mkdir(parents=True, exist_ok=True)
        log_path = data_dir / "tor.log"
        torrc_path = data_dir / "torrc"
        if log_path.exists():
            try:
                log_path.unlink()
            except OSError:
                pass

        torrc_lines = [
            f"SocksPort 127.0.0.1:{port}",
            f"DataDirectory {data_dir}",
            f"Log notice file {log_path}",
            f"ExitNodes {{{country}}}",
            "StrictNodes 1",
            "ClientOnly 1",
        ]
        if geoip:
            torrc_lines.append(f"GeoIPFile {geoip}")
            geoip6 = geoip.parent / "geoip6"
            if geoip6.is_file():
                torrc_lines.append(f"GeoIPv6File {geoip6}")
        torrc_path.write_text("\n".join(torrc_lines) + "\n", encoding="utf-8")

        creationflags = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
        try:
            proc = subprocess.Popen(
                [str(tor_exe), "-f", str(torrc_path)],
                cwd=str(tor_exe.parent),
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                creationflags=creationflags,
                start_new_session=(os.name != "nt"),
            )
        except OSError as exc:
            print(f"[{country.upper()}] failed to start tor: {exc}")
            continue
        inst = {
            "country": country,
            "port": port,
            "pid": proc.pid,
            "started_at": time.time(),
        }
        instances.append(inst)
        print(f"[{country.upper()}] started port={port} pid={proc.pid}")

    if not instances:
        print("No instances running.")
        save_state([])
        write_proxies_file([])
        return

    # Wait (in parallel) for bootstrapping so the service verifies usable exits.
    pending = {inst["country"]: inst for inst in instances}
    deadline = time.time() + args.wait
    last_report = 0.0
    while pending and time.time() < deadline:
        for country in list(pending):
            if bootstrap_state(country) == "ready":
                print(f"[{country.upper()}] bootstrapped 100%")
                pending.pop(country)
            elif not is_pid_alive(int(pending[country]["pid"])):
                log_hint = TOR_DATA / country / "tor.log"
                print(f"[{country.upper()}] tor exited early — check {log_hint}")
                pending.pop(country)
        if pending and time.time() - last_report >= 10:
            last_report = time.time()
            remaining = ", ".join(sorted(c.upper() for c in pending))
            print(f"waiting for bootstrap: {remaining}")
        if pending:
            time.sleep(2)

    alive_instances = [inst for inst in instances if is_pid_alive(int(inst["pid"]))]
    save_state(alive_instances)
    write_proxies_file(alive_instances)
    print(
        f"\nDone. {len(alive_instances)} instance(s) running; "
        f"tor-proxies.txt updated (service picks it up on the next cycle)."
    )
    if pending:
        print("Note: some instances were still bootstrapping; they will appear once ready.")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run local Tor instances pinned to countries and feed tor-proxies.txt."
    )
    parser.add_argument("--countries", help="Comma-separated ISO-2 codes, e.g. us,de,jp")
    parser.add_argument(
        "--base-port", type=int, default=9701, help="First SOCKS port (default 9701)"
    )
    parser.add_argument(
        "--tor-exe", help="Path to tor.exe (default: auto-detect in .\\tor)"
    )
    parser.add_argument(
        "--wait",
        type=float,
        default=150.0,
        help="Seconds to wait for bootstrapping (default 150)",
    )
    parser.add_argument("--status", action="store_true", help="Show instance status and exit")
    parser.add_argument("--stop", action="store_true", help="Stop all instances and exit")
    args = parser.parse_args()

    if args.status:
        cmd_status()
        return
    if args.stop:
        cmd_stop()
        return
    cmd_start(args)


if __name__ == "__main__":
    main()
